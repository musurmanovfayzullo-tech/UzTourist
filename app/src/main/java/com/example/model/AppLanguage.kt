enum class AppLanguage(
    val code: String,
    val displayName: String,
    val flag: String,
    val nativeName: String,
    val greeting: String
) {
    UZ("uz", "O'zbekcha", "🇺🇿", "O'zbek", "Xush kelibsiz!"),
    EN("en", "English", "🇬🇧", "English", "Welcome!"),
    RU("ru", "Русский", "🇷🇺", "Русский", "Добро пожаловать!"),
    DE("de", "Deutsch", "🇩🇪", "Deutsch", "Willkommen!"),
    FR("fr", "Français", "🇫🇷", "Français", "Bienvenue!"),
