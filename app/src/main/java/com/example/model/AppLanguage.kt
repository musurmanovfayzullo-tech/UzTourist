    TR("tr", "Türkçe", "🇹🇷", "Türkçe", "Hoş geldiniz!"),
    ZH("zh", "中文", "🇨🇳", "中文", "欢迎！"),
    JA("ja", "日本語", "🇯🇵", "日本語", "ようこそ！");

    companion object {
        var currentLanguage: AppLanguage
            get() = AppLanguageState.currentLanguage
            set(value) {
                AppLanguageState.currentLanguage = value
            }
    }
}

object AppLanguageState {
    var currentLanguage by mutableStateOf(AppLanguage.UZ)
}

val LocalAppLanguage = compositionLocalOf { AppLanguage.UZ }

@Composable
fun appString(key: String): String {
    val lang = LocalAppLanguage.current
    return AppStrings.get(key, lang)
}

